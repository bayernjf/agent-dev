import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import type { Credentials } from './credentials.js';
import type { ProjectResources } from './project-resources.js';

/**
 * Credential keys that may be written into the agent workspace .env.
 *
 * Whitelist, intentionally empty (2026-11-02 review P1-1): the previous
 * blacklist excluded only four keys, so SUPABASE_SERVICE_ROLE_KEY and any
 * user-added credential landed in plaintext inside a workspace where the
 * agent runs with bypassed permissions (--yolo / --dangerously-skip-
 * permissions). Agents receive provider resource identifiers (project ids,
 * URLs) below, which are not credentials. A key may join this list only once
 * the Env Contract (docs/environment-and-connectors.md) classifies it as
 * non-secret.
 */
const WORKSPACE_CREDENTIAL_ALLOWLIST: readonly string[] = [];

export function generateEnvFile(workspacePath: string, credentials: Credentials, resources: ProjectResources | null, appName: string) {
  const lines = ['# Generated by Agent-Dev. Do not commit this file.', `APP_NAME=${appName}`, 'NODE_ENV=development'];
  if (resources) for (const [provider, values] of Object.entries(resources.providers)) for (const [key, value] of Object.entries(values)) {
    if (typeof value !== 'string' || /key|token|secret|password|database|connection/i.test(key)) continue;
    lines.push(`${provider.toUpperCase()}_${key.replace(/([a-z])([A-Z])/g, '$1_$2').toUpperCase()}=${value}`);
  }
  for (const [key, value] of Object.entries(credentials)) {
    if (WORKSPACE_CREDENTIAL_ALLOWLIST.includes(key)) lines.push(`${key}=${value}`);
  }
  writeFileSync(join(workspacePath, '.env'), `${lines.join('\n')}\n`, { mode: 0o600 });
}
